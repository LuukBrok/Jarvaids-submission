"""Build the board z-order fixture that both implementations are checked against.

The z-order rule in `spec/canvas-layout.md` is written twice: once in
`Service._board_order` and once in `boardOrder` in `session-sync.mjs`. They
agree today and nothing keeps them agreeing, which is the pattern AGENTS.md
opens on. When they drift, two people in the same meeting see a different item
on top, and that gets blamed on the projector.

This builds a board through the real `Service`, no hand-written expectations,
and writes the server's own snapshot including its `board_order`.
`tests/board-order-unit.mjs` runs the client's ordering over the same records
and compares; `tests/test_board_order.py` regenerates this file and fails if it
differs, so the fixture cannot go stale while the server's rule moves.

The board is built so that all three sort keys are load-bearing, because a
fixture that any plausible sort satisfies would prove nothing:

- four records the layout engine placed at one instant, three of which still
  share that instant at the end, and whose identifiers deliberately sort in a
  different order from the order they were created in, so removing the
  identifier tie-break changes the answer;
- two more the engine placed later, so `placed_at` is load-bearing inside the
  machine group, one of them a provisional proposal rather than an item;
- two a person placed, also sharing an instant and also in a different
  identifier order from creation order;
- one a person placed before the engine placed anything, so `hand_placed`
  outranks `placed_at` rather than merely agreeing with it. Without it the whole
  board sorts correctly on time alone and dropping the first key changes
  nothing, which is how a check that cannot fail gets written;
- one the engine placed that a person then moved, so it flips to hand-placed
  and sorts to the top;
- one record nobody placed, which must not appear in the order at all.

The session is paused in the snapshot, and that is not an oversight: the
fixture's clock jumps past the session lease, and a move is deliberately not
gated on an active session, because gating it would freeze the board every time
the facilitator stepped out of the room. See `Service._place`.

Identifiers are normally random, which would make the file differ on every run
and make a regeneration check impossible. The generator installs a deterministic
allocator for the duration of the build, which is the only thing here that is
not exactly what a real session does. It changes the names of records, not the
rule being pinned.

Run it directly to rewrite the fixture after a deliberate change to the rule.
"""
import json
import sys
import tempfile
from pathlib import Path

# Runnable directly as well as under unittest discovery, which is how the
# fixture gets regenerated after a deliberate change to the rule.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from genai_server import service as service_module
from genai_server.service import Service

FIXTURE = Path(__file__).resolve().parent / 'board-order-fixture.json'
SESSION_ID = 'board-order-fixture-session'
TOKEN = 'board-order-fixture-facilitator-token-01'
NOTE = ('Generated by tests/make_order_fixture.py. Do not hand-edit: '
        'tests/test_board_order.py regenerates it and compares, and '
        'tests/board-order-unit.mjs checks the client agrees with board_order.')

# Creation order, then identifier. The two differ on purpose: if they matched,
# a sort that dropped the identifier tie-break would still produce the fixture
# order, and the check could not fail.
MACHINE_EARLY = ('quilt', 'marlow', 'anchor', 'kestrel')
MACHINE_LATE = 'thistle'
HAND = ('willow', 'bramble')
HAND_EARLY = 'osprey'
MOVED = 'quilt'
UNPLACED = 'fig'
PROPOSAL = 'record-vellum'


class Ids:
    """Deterministic identifiers, queued in the order the service allocates them.

    Anything the service allocates that the fixture did not name gets a spare,
    so an unexpected extra allocation shows up as a spare in the file rather
    than as a silently shifted name.
    """

    def __init__(self):
        self.queue = []
        self.spares = 0

    def expect(self, *names):
        self.queue.extend(names)

    def __call__(self):
        if self.queue:
            return self.queue.pop(0)
        self.spares += 1
        return 'fixture-spare-%08d' % self.spares


def build(directory):
    """One session, built through the public service surface, snapshot returned."""
    ids = Ids()
    original = service_module.new_id
    service_module.new_id = ids
    try:
        clock = {'now': 1000.0}
        service = Service(Path(directory) / 'state.sqlite3', clock=lambda: clock['now'])
        requests = {'n': 0}

        def cmd(operation, payload):
            requests['n'] += 1
            request_id = 'fixture-request-%04d' % requests['n']
            snapshot = service.snapshot(SESSION_ID, TOKEN)
            payload = dict(payload)
            if operation == 'session.activate':
                payload['expected_session_revision'] = snapshot['session']['revision']
            sequence = (snapshot['next_control_sequence']
                        if operation in service.CONTROL_COMMANDS else None)
            return service.command(SESSION_ID, TOKEN, request_id, operation, payload, sequence)['result']

        def note(name, text):
            """A source, its proposal and the accepted item, as a real note arrives."""
            ids.expect('source-' + name, 'proposal-' + name)
            proposal = cmd('source.text', {'text': text})['proposal']
            ids.expect('record-' + name)
            return cmd('proposal.review', {'proposal_id': proposal['id'],
                                           'expected_revision': proposal['revision'],
                                           'decision': 'accept'})['item']

        def place(names, origin, revisions=None):
            revisions = revisions or {}
            return cmd('item.place', {'origin': origin, 'placements': [
                {'id': name, 'x': 10.0 * index, 'y': 20.0 * index,
                 'expected_position_revision': revisions.get(name, 0)}
                for index, name in enumerate(names)]})

        ids.expect('actor-facilitator')
        service.create_session({'session_id': SESSION_ID, 'title': 'Board order fixture',
                                'owner_name': 'Facilitator', 'owner_token': TOKEN})
        version = service.snapshot(SESSION_ID, TOKEN)['session']['policy_version']
        cmd('consent.acknowledge', {'policy_version': version})
        cmd('session.activate', {'policy_version': version})

        for name in MACHINE_EARLY:
            note(name, 'Machine placed: ' + name)
        # Created before thistle and sorting after it, so the later machine pair
        # exercises the tie-break as well. Never reviewed, so it stays on the
        # board as a proposal: provisional records are placed too.
        ids.expect('source-vellum', PROPOSAL)
        cmd('source.text', {'text': 'Still provisional'})
        note(MACHINE_LATE, 'Machine placed later: ' + MACHINE_LATE)
        for name in HAND:
            note(name, 'Hand placed: ' + name)
        note(HAND_EARLY, 'Hand placed first: ' + HAND_EARLY)
        note(UNPLACED, 'Never placed: ' + UNPLACED)

        # Placed by a person before the engine placed anything, and still below
        # everything the engine placed: what people put down sits above the
        # engine's guesses whatever the clock says.
        clock['now'] = 1500.0
        place(['record-' + HAND_EARLY], 'human')
        clock['now'] = 2000.0
        place(['record-' + name for name in MACHINE_EARLY], 'machine')
        clock['now'] = 2100.0
        place(['record-' + MACHINE_LATE, PROPOSAL], 'machine')
        clock['now'] = 3000.0
        place(['record-' + name for name in HAND], 'human')
        clock['now'] = 4000.0
        # A person moves what the engine had placed: hand-placed from now on,
        # and the most recently touched, so it belongs on top.
        place(['record-' + MOVED], 'human', {'record-' + MOVED: 1})

        return service.snapshot(SESSION_ID, TOKEN)
    finally:
        service_module.new_id = original


def render():
    with tempfile.TemporaryDirectory() as directory:
        fixture = {'note': NOTE, 'snapshot': build(directory)}
    return json.dumps(fixture, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


if __name__ == '__main__':
    FIXTURE.write_text(render(), encoding='utf-8')
    print('Wrote %s' % FIXTURE)
